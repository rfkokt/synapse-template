#!/usr/bin/env node
/* global console, process */
/* eslint no-undef: "off" */

/**
 * Create Standalone MFE (Multi-Repo)
 *
 * Usage:
 *   node tools/scripts/create-standalone-mfe.mjs <nama-mfe> --port=<port>
 *
 * Example:
 *   node tools/scripts/create-standalone-mfe.mjs reporting-mfe --port=4006
 *
 * What it does:
 *   1. Generates MFE inside monorepo (via Nx generator)
 *   2. Copies the generated MFE to ../  (parent of monorepo)
 *   3. Creates .npmrc pointing to Verdaccio
 *   4. Replaces workspace:* → ^0.1.0 in package.json
 *   5. Uses standalone tsconfig if available
 *   6. Registers MFE in Shell's remotes.json (already done by generator)
 */

import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MONOREPO_ROOT = path.resolve(__dirname, '../..');

// ── Parse args ──
const args = process.argv.slice(2);
const mfeName = args.find((a) => !a.startsWith('--'));
const portArg = args.find((a) => a.startsWith('--port='));
const port = portArg ? parseInt(portArg.split('=')[1], 10) : null;
const targetDirArg = args.find((a) => a.startsWith('--target='));
const targetParent = targetDirArg
  ? path.resolve(targetDirArg.split('=')[1])
  : path.resolve(MONOREPO_ROOT, '..');

if (!mfeName || !port) {
  console.error(`
╔══════════════════════════════════════════════════════╗
║  Create Standalone MFE (Multi-Repo)                  ║
╠══════════════════════════════════════════════════════╣
║                                                      ║
║  Usage:                                              ║
║    pnpm run create:standalone <name> --port=<port>   ║
║                                                      ║
║  Example:                                            ║
║    pnpm run create:standalone reporting-mfe --port=4006║
║                                                      ║
║  Options:                                            ║
║    --target=<path>  Target parent dir (default: ../) ║
║                                                      ║
╚══════════════════════════════════════════════════════╝
`);
  process.exit(1);
}

const sourceDir = path.join(MONOREPO_ROOT, 'apps', mfeName);
const targetDir = path.join(targetParent, mfeName);

console.log(`
┌──────────────────────────────────────────
│ 🚀 Creating Standalone MFE: ${mfeName}
│    Port: ${port}
│    Target: ${targetDir}
└──────────────────────────────────────────
`);

// ── Step 1: Generate in monorepo ─────────────────
console.log('📦 Step 1/5: Generating MFE in monorepo...');
try {
  execSync(`pnpm nx g @synapse/tools:mfe ${mfeName} --port=${port}`, {
    cwd: MONOREPO_ROOT,
    stdio: 'inherit',
  });
} catch {
  console.error('❌ Failed to generate MFE in monorepo.');
  process.exit(1);
}

// ── Step 2: Copy to standalone location ──────────
console.log(`\n📁 Step 2/5: Copying to ${targetDir}...`);
if (fs.existsSync(targetDir)) {
  console.error(`❌ Target directory already exists: ${targetDir}`);
  console.error('   Delete it first or pick a different name.');
  process.exit(1);
}

// Recursive copy
fs.cpSync(sourceDir, targetDir, { recursive: true });
console.log('   ✅ Copied successfully.');

// ── Step 3: Create .npmrc ─────────────────────────
console.log('\n📝 Step 3/5: Creating .npmrc for Verdaccio...');
const npmrcContent = `# Auto-generated by create-standalone-mfe
@synapse:registry=http://localhost:4873/
//localhost:4873/:_authToken="anonymous"
auto-install-peers=true
strict-peer-dependencies=false
`;
fs.writeFileSync(path.join(targetDir, '.npmrc'), npmrcContent);
console.log('   ✅ .npmrc created.');

// ── Step 4: Replace workspace:* → ^0.1.0 ────────
console.log('\n🔧 Step 4/5: Replacing workspace:* with ^0.1.0...');
const pkgJsonPath = path.join(targetDir, 'package.json');
let pkgContent = fs.readFileSync(pkgJsonPath, 'utf-8');
pkgContent = pkgContent.replace(/"workspace:\*"/g, '"^0.1.0"');
fs.writeFileSync(pkgJsonPath, pkgContent);
console.log('   ✅ Dependencies updated.');

// ── Step 5: Use standalone tsconfig ───────────────
console.log('\n⚙️  Step 5/5: Setting up tsconfig...');
const standaloneTsconfig = path.join(targetDir, 'tsconfig.standalone.json');
const targetTsconfig = path.join(targetDir, 'tsconfig.json');
if (fs.existsSync(standaloneTsconfig)) {
  fs.copyFileSync(standaloneTsconfig, targetTsconfig);
  fs.unlinkSync(standaloneTsconfig);
  console.log('   ✅ Using standalone tsconfig.');
} else {
  console.log('   ⚠️  No standalone tsconfig found, keeping default.');
}

// ── Done! ─────────────────────────────────────────
console.log(`
┌──────────────────────────────────────────────────────
│ ✅ Standalone MFE created!
│
│ Next steps:
│   1. Start Verdaccio:    pnpm run verdaccio:start
│   2. Publish libs:       pnpm run libs:publish:local
│   3. Install deps:       cd ${targetDir} && pnpm install
│   4. Run MFE:            pnpm run serve
│   5. Open Shell:         http://localhost:4000/${mfeName}
│
│ Shell remotes.json sudah otomatis terdaftar oleh generator.
└──────────────────────────────────────────────────────
`);
